def load_seen_bounties():
    """Load previously seen bounty URLs from the state file."""
    if os.path.exists(STATE_FILE):
        try:
            with open(STATE_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                # Handle potential list or nested dict structure for URL extraction
                if isinstance(data, list):
                    # Assume URLs are direct strings or dicts with 'url'/'html_url'
                    return set(str(entry["url"] if isinstance(entry, dict) else entry) for entry in data if entry)
                elif isinstance(data, dict):
                    # Fallback for nested state structures
                    items = data.get("items", [])
                    return set(str(e.get("url", e.get("html_url", e))) for e in items if e)
                else:
                    return set(data)
        except Exception as e:
            print(f"Error loading state file: {e}")
            return set()
    return set()

def save_seen_bounties(seen_urls):
    """Save the updated list of seen bounty URLs."""
    try:
        with open(STATE_FILE, "w", encoding="utf-8") as f:
            # Normalize to a list for consistent JSON serialization
            json.dump(list(seen_urls), f, indent=2)
    except Exception as e:
        print(f"Error saving state file: {e}")

def search_github(query, token=None):
    """Fetch search results from GitHub Issues API."""
    params = {"q": query, "per_page": 15}
    url = f"https://api.github.com/search/issues?{urllib.parse.urlencode(params)}"
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "MyPersonalBountyScout",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
        
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=20) as response:
            return json.loads(response.read().decode("utf-8"))
    except Exception as e:
        print(f"GitHub Search API Error for query '{query}': {e}")
        return {}

def is_clean_candidate(item):
    """Triage logic to filter out noisy, assigned, closed, or spam tasks."""
    if not item:
        return False
        
    # 1. Skip if already a Pull Request (handle nested dict vs boolean)
    pull_request = item.get("pull_request")
    if pull_request:
        return False
    
    # 2. Skip if already assigned (handle list of assignees)
    assignees = item.get("assignees")
    if assignees and len(assignees) > 0:
        return False
        
    # 3. Skip if thread is overcrowded (highly competitive)
    comments = item.get("comments")
    if comments and int(comments) > MAX_COMMENTS:
        return False
        
    title = str(item.get("title", "")).strip().lower()
    body = str(item.get("body", "")).strip().lower()
    
    # 4. Skip cryptocurrency/article writing/spam keywords
    blocklist = [
        "airdrop", "referral", "casino", "gambling", "trading bot", 
        "blog post", "article writing", "tutorial proposal", "content creator"
    ]
    if any(term in title or term in body for term in blocklist):
        return False
        
    return True

def send_telegram_notification(token, chat_id, message):
    """Send a notification message via Telegram Bot API."""
    url = f"https://api.telegram.org/bot{token}/sendMessage"
    payload = {
        "chat_id": chat_id,
        "text": message,
        "parse_mode": "Markdown",
        "disable_web_page_preview": False
    }
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as response:
            print("Telegram notification sent successfully.")
    except Exception as e:
        print(f"Failed to send Telegram notification: {e}")

